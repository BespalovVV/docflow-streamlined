function generateBlankTxt(title = 'Документ') {
  return Buffer.from(`${title}\nСоздан в DocFlow: ${new Date().toLocaleString('ru-RU')}\n\n`, 'utf8');
}

function generateBlankCsv(title = 'Данные') {
  return Buffer.from(`\uFEFF# ${title}\nСтолбец 1,Столбец 2,Столбец 3\nЗначение 1,Значение 2,Значение 3\n`, 'utf8');
}

function generateBlankMd(title = 'Новый документ') {
  return Buffer.from(`# ${title}\n\n*Создан в DocFlow: ${new Date().toLocaleString('ru-RU')}*\n\n## Раздел 1\n\nТекст заметки...\n`, 'utf8');
}

